-- Tenant ownership is application-level because tenant records live in system_db.
-- Relationships inside catalog_db use tenant-qualified foreign keys to prevent cross-tenant links.

CREATE TABLE catalog_sites (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    site_key VARCHAR(100) NOT NULL,
    default_locale VARCHAR(10) NOT NULL DEFAULT 'en' CHECK (default_locale IN ('en', 'bn')),
    publication_state VARCHAR(20) NOT NULL DEFAULT 'DRAFT' CHECK (publication_state IN ('DRAFT', 'PUBLISHED')),
    published_at TIMESTAMPTZ,
    published_by VARCHAR(255),
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(255) NOT NULL,
    updated_by VARCHAR(255) NOT NULL,
    CONSTRAINT uq_catalog_sites_tenant_key UNIQUE (tenant_id, site_key),
    CONSTRAINT uq_catalog_sites_tenant_id UNIQUE (tenant_id, id),
    CONSTRAINT ck_catalog_sites_publication CHECK (
        (publication_state = 'DRAFT' AND published_at IS NULL AND published_by IS NULL)
        OR (publication_state = 'PUBLISHED' AND published_at IS NOT NULL AND published_by IS NOT NULL)
    )
);

