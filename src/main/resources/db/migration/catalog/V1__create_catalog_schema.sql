    CONSTRAINT fk_catalog_organization_logo FOREIGN KEY (tenant_id, logo_media_id) REFERENCES catalog_media_assets (tenant_id, id) ON DELETE RESTRICT,
    CONSTRAINT ck_catalog_organization_publication CHECK (
        (publication_state = 'DRAFT' AND published_at IS NULL AND published_by IS NULL)
        OR (publication_state = 'PUBLISHED' AND published_at IS NOT NULL AND published_by IS NOT NULL)
    )
);

CREATE TABLE catalog_gallery_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    gallery_type VARCHAR(30) NOT NULL CHECK (gallery_type IN ('PHOTO', 'CERTIFICATION', 'VIDEO')),
    title VARCHAR(255) NOT NULL,
    media_id BIGINT NOT NULL,
    display_order INTEGER NOT NULL DEFAULT 0 CHECK (display_order >= 0),
    publication_state VARCHAR(20) NOT NULL DEFAULT 'DRAFT' CHECK (publication_state IN ('DRAFT', 'PUBLISHED')),
    published_at TIMESTAMPTZ,
    published_by VARCHAR(255),
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(255) NOT NULL,
    updated_by VARCHAR(255) NOT NULL,
    CONSTRAINT uq_catalog_gallery_tenant_id UNIQUE (tenant_id, id),
    CONSTRAINT fk_catalog_gallery_media FOREIGN KEY (tenant_id, media_id) REFERENCES catalog_media_assets (tenant_id, id) ON DELETE RESTRICT,
    CONSTRAINT ck_catalog_gallery_publication CHECK (
        (publication_state = 'DRAFT' AND published_at IS NULL AND published_by IS NULL)
        OR (publication_state = 'PUBLISHED' AND published_at IS NOT NULL AND published_by IS NOT NULL)
    )
);

